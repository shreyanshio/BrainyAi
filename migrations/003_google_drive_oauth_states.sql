CREATE TABLE IF NOT EXISTS google_drive_oauth_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_nonce TEXT NOT NULL UNIQUE,
    state_hash TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    operation TEXT NOT NULL DEFAULT 'drive_owner_oauth',
    expires_at TIMESTAMPTZ NOT NULL,
    consumed BOOLEAN DEFAULT FALSE,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_drive_oauth_states_nonce ON google_drive_oauth_states(state_nonce);
CREATE INDEX IF NOT EXISTS idx_drive_oauth_states_expires ON google_drive_oauth_states(expires_at);

ALTER TABLE google_drive_oauth_states ENABLE ROW LEVEL SECURITY;

-- Deny all client/anon/authenticated direct access (backend service role only)
DROP POLICY IF EXISTS "Deny direct client access to drive oauth states" ON google_drive_oauth_states;
CREATE POLICY "Deny direct client access to drive oauth states"
    ON google_drive_oauth_states
    FOR ALL
    TO anon, authenticated
    USING (false);

DROP POLICY IF EXISTS "service_role_all_drive_oauth_states" ON google_drive_oauth_states;
CREATE POLICY "service_role_all_drive_oauth_states"
    ON google_drive_oauth_states
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);
