--   BRAINY — Production Supabase Schema & Row-Level Security (RLS)
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
-- Run this complete script in your Supabase SQL Editor.
-- It initializes all tables, performance indexes, and security policies
-- for both the Telegram AI Study Bot and the Web Companion.

-- Enable UUID extension if not already present
create extension if not exists "uuid-ossp";

-- ── 1. TELEGRAM BOT USERS ───────────────────────────────────────────
-- Persistent user registry for Telegram bot communication and broadcasts
create table if not exists bot_users (
  chat_id     bigint primary key,
  chat_type   text default 'private',   -- 'private' or 'group'
  username    text,
  first_name  text,
  joined_at   timestamptz default now(),
  last_seen   timestamptz default now()
);

create index if not exists idx_bot_users_last_seen on bot_users(last_seen desc);

-- ── 2. USER MEMORY & STATS ──────────────────────────────────────────
-- Stores long-term user context, custom liked notes, and gamification
create table if not exists user_memory (
  user_id      bigint primary key,
  first_name   text        default '',
  username     text        default '',
  level        text        default 'Beginner',
  score        int         default 0,
  total        int         default 0,
  joined_at    timestamptz default now(),
  history      jsonb       default '[]'::jsonb,   -- last 20 messages context
  ask_history  jsonb       default '[]'::jsonb,   -- last 10 /ask messages
  liked_notes  jsonb       default '[]'::jsonb,   -- persistent user notes
  updated_at   timestamptz default now()
);

create index if not exists idx_user_memory_user_id on user_memory(user_id);

-- ── 3. USER LOGINS (TELEMETRY & AUDIT LOGS) ─────────────────────────
-- Tracks all authenticated login events for real admin analytics
create table if not exists user_logins (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null,
  username    text,
  first_name  text,
  login_type  text not null,                       -- 'google', 'telegram', 'telegram_webapp', 'web', 'student_pass'
  ip_address  text,
  user_agent  text,
  created_at  timestamptz default now()
);

create index if not exists idx_user_logins_user_id on user_logins(user_id);
create index if not exists idx_user_logins_created_at on user_logins(created_at desc);

-- ── 4. CHAT SESSIONS & CONVERSATIONS ────────────────────────────────
-- Stores study chat workspaces for web students
-- Note: chat session titles can be stored encrypted / hashed
create table if not exists chat_sessions (
  id          uuid primary key default uuid_generate_v4(),
  user_id     bigint not null,
  title       text not null default 'New Study Session',
  created_at  timestamptz default now()
);

create index if not exists idx_chat_sessions_user_id on chat_sessions(user_id);
create index if not exists idx_chat_sessions_created_at on chat_sessions(created_at desc);

-- ── 5. CHAT MESSAGES ────────────────────────────────────────────────
-- Stores conversational turns within a study session
-- Note: user questions can be stored with cryptographic masking
create table if not exists chat_messages (
  id          bigint generated by default as identity primary key,
  session_id  uuid not null references chat_sessions(id) on delete cascade,
  role        text not null check (role in ('user', 'assistant', 'system')),
  content     text not null,
  created_at  timestamptz default now()
);

create index if not exists idx_chat_messages_session_id on chat_messages(session_id);
create index if not exists idx_chat_messages_created_at on chat_messages(created_at asc);

-- ── 6. USER PREFERENCES ─────────────────────────────────────────────
-- Persistent UI customizations (theme, accent, typography, density, study defaults)
create table if not exists user_preferences (
  user_id      bigint primary key,
  preferences  jsonb not null default '{}'::jsonb,
  updated_at   timestamptz default now()
);

-- ── 7. NATIVE QUIZ & EXAM TRACKING ──────────────────────────────────
-- Tracks interactive multiple-choice questions & per-chat leaderboards
create table if not exists quiz_polls (
  poll_id            text primary key,
  chat_id            bigint not null,
  correct_option_id  int not null,
  subject            text,
  created_at         timestamptz default now()
);

create table if not exists quiz_scores (
  chat_id         bigint not null,
  user_id         bigint not null,
  username        text,
  correct_count   int default 0,
  total_answered  int default 0,
  updated_at      timestamptz default now(),
  primary key (chat_id, user_id)
);

-- ── 8. ROW LEVEL SECURITY (RLS) POLICIES ────────────────────────────
-- Enable Row Level Security on all application tables
alter table bot_users enable row level security;
alter table user_memory enable row level security;
alter table user_logins enable row level security;
alter table chat_sessions enable row level security;
alter table chat_messages enable row level security;
alter table user_preferences enable row level security;
alter table quiz_polls enable row level security;
alter table quiz_scores enable row level security;

-- The Python/Flask backend and Telegram bot connect using the Supabase
-- service_role key, which inherently bypasses RLS for server-side authority.
-- The following policies secure direct client-side / anon access:

-- Public service access policies:
drop policy if exists "Service role full access on bot_users" on bot_users;
create policy "Service role full access on bot_users"
  on bot_users for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on user_memory" on user_memory;
create policy "Service role full access on user_memory"
  on user_memory for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on user_logins" on user_logins;
create policy "Service role full access on user_logins"
  on user_logins for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on chat_sessions" on chat_sessions;
create policy "Service role full access on chat_sessions"
  on chat_sessions for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on chat_messages" on chat_messages;
create policy "Service role full access on chat_messages"
  on chat_messages for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on user_preferences" on user_preferences;
create policy "Service role full access on user_preferences"
  on user_preferences for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on quiz_polls" on quiz_polls;
create policy "Service role full access on quiz_polls"
  on quiz_polls for all
  using (auth.role() = 'service_role');

drop policy if exists "Service role full access on quiz_scores" on quiz_scores;
create policy "Service role full access on quiz_scores"
  on quiz_scores for all
  using (auth.role() = 'service_role');
