-- This script safely updates existing tables (adding missing columns)
-- and creates any missing tables, indexes, and Row-Level Security policies.
-- Safe to run repeatedly in the Supabase SQL Editor.

-- Enable UUID extension if not already present
create extension if not exists "uuid-ossp";

-- ── 1. TELEGRAM BOT USERS ───────────────────────────────────────────
create table if not exists bot_users (
  chat_id     bigint primary key,
  chat_type   text default 'private',
  username    text,
  first_name  text,
  joined_at   timestamptz default now(),
  last_seen   timestamptz default now()
);

-- Ensure all columns exist if the table was created earlier
alter table bot_users add column if not exists chat_type text default 'private';
alter table bot_users add column if not exists username text;
alter table bot_users add column if not exists first_name text;
alter table bot_users add column if not exists joined_at timestamptz default now();
alter table bot_users add column if not exists last_seen timestamptz default now();

create index if not exists idx_bot_users_last_seen on bot_users(last_seen desc);

-- ── 2. USER MEMORY & STATS ──────────────────────────────────────────
create table if not exists user_memory (
  user_id      bigint primary key,
  first_name   text        default '',
  username     text        default '',
  level        text        default 'Beginner',
  score        int         default 0,
  total        int         default 0,
  joined_at    timestamptz default now(),
  history      jsonb       default '[]'::jsonb,
  ask_history  jsonb       default '[]'::jsonb,
  liked_notes  jsonb       default '[]'::jsonb,
  updated_at   timestamptz default now()
);

-- Ensure columns exist if user_memory already existed
alter table user_memory add column if not exists first_name text default '';
alter table user_memory add column if not exists username text default '';
alter table user_memory add column if not exists level text default 'Beginner';
alter table user_memory add column if not exists score int default 0;
alter table user_memory add column if not exists total int default 0;
alter table user_memory add column if not exists joined_at timestamptz default now();
alter table user_memory add column if not exists history jsonb default '[]'::jsonb;
alter table user_memory add column if not exists ask_history jsonb default '[]'::jsonb;
alter table user_memory add column if not exists liked_notes jsonb default '[]'::jsonb;
alter table user_memory add column if not exists preferences jsonb not null default '{}'::jsonb;
alter table user_memory add column if not exists updated_at timestamptz default now();

create index if not exists idx_user_memory_user_id on user_memory(user_id);

-- ── 3. USER LOGINS (TELEMETRY & AUDIT LOGS) ─────────────────────────
create table if not exists user_logins (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null,
  username    text,
  first_name  text,
  login_type  text not null default 'web',
  ip_address  text,
  user_agent  text,
  created_at  timestamptz default now()
);

-- Safely add created_at and other columns if table already existed
alter table user_logins add column if not exists username text;
alter table user_logins add column if not exists first_name text;
alter table user_logins add column if not exists login_type text not null default 'web';
alter table user_logins add column if not exists ip_address text;
alter table user_logins add column if not exists user_agent text;
alter table user_logins add column if not exists created_at timestamptz default now();

create index if not exists idx_user_logins_user_id on user_logins(user_id);
create index if not exists idx_user_logins_created_at on user_logins(created_at desc);

-- ── 4. CHAT SESSIONS & CONVERSATIONS ────────────────────────────────
create table if not exists chat_sessions (
  id          uuid primary key default uuid_generate_v4(),
  user_id     bigint not null,
  title       text not null default 'New Study Session',
  created_at  timestamptz default now()
);

-- Safely add created_at and title if table already existed
alter table chat_sessions add column if not exists title text not null default 'New Study Session';
alter table chat_sessions add column if not exists created_at timestamptz default now();

create index if not exists idx_chat_sessions_user_id on chat_sessions(user_id);
create index if not exists idx_chat_sessions_created_at on chat_sessions(created_at desc);

-- ── 5. CHAT MESSAGES ────────────────────────────────────────────────
create table if not exists chat_messages (
  id          bigint generated by default as identity primary key,
  session_id  uuid not null references chat_sessions(id) on delete cascade,
  role        text not null check (role in ('user', 'assistant', 'system')),
  content     text not null,
  created_at  timestamptz default now()
);

-- Safely add created_at if table already existed
alter table chat_messages add column if not exists created_at timestamptz default now();

create index if not exists idx_chat_messages_session_id on chat_messages(session_id);
create index if not exists idx_chat_messages_created_at on chat_messages(created_at asc);

-- ── 6. USER PREFERENCES ─────────────────────────────────────────────
create table if not exists user_preferences (
  user_id      bigint primary key,
  preferences  jsonb not null default '{}'::jsonb,
  updated_at   timestamptz default now()
);

alter table user_preferences add column if not exists preferences jsonb not null default '{}'::jsonb;
alter table user_preferences add column if not exists updated_at timestamptz default now();

-- ── 7. NATIVE QUIZ & EXAM TRACKING ──────────────────────────────────
create table if not exists quiz_polls (
  poll_id            text primary key,
  chat_id            bigint not null,
  correct_option_id  int not null,
  subject            text,
  created_at         timestamptz default now()
);

alter table quiz_polls add column if not exists created_at timestamptz default now();

create table if not exists quiz_scores (
  chat_id         bigint not null,
  user_id         bigint not null,
  username        text,
  correct_count   int default 0,
  total_answered  int default 0,
  updated_at      timestamptz default now(),
  primary key (chat_id, user_id)
);

alter table quiz_scores add column if not exists updated_at timestamptz default now();

-- ── 8. ROW LEVEL SECURITY (RLS) POLICIES ────────────────────────────
alter table bot_users enable row level security;
alter table user_memory enable row level security;
alter table user_logins enable row level security;
alter table chat_sessions enable row level security;
alter table chat_messages enable row level security;
alter table user_preferences enable row level security;
alter table quiz_polls enable row level security;
alter table quiz_scores enable row level security;

